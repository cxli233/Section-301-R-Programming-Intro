# Example script. 
# Usage: list numbers from a starting value to an ending value by some increment. 
# Date created: 2026-06-16. 
# Author: Chenxin Li.
# Last Modified: 2026-06-16. 
# Input: A starting value, an ending value, and increment 
# Output: A vector 
# Required packages: none. 

start <- 0
end <- 100
increment <- 1

seq(from = start, to = end, by = increment)
